/* dbgauth.c -- see dbgauth.h for the wire format and the replay argument.
 *
 * Built into every image, but the envelope code only exists under
 * -DDBG_AUTH (the `dbg` default; `make dbg DBG_NO_AUTH=1` opts out). The
 * peer-MAC tracking and the counters are always present so emac.c can use
 * them unconditionally.
 *
 * Single owner: called only from emac_poll(), which one core services at a
 * time (see emac.c's RX notes), so no locking here.
 */
#include <stdint.h>
#include "dbgauth.h"
#include "emac.h"

static volatile uint32_t g_stats[DBGAUTH_ST_N];
static uint8_t  g_peer[6];
static int      g_peer_valid;

void dbgauth_count(uint32_t which)
{
	if (which < DBGAUTH_ST_N)
		g_stats[which]++;
}

const volatile uint32_t *dbgauth_stats(void)
{
	return g_stats;
}

const uint8_t *dbgauth_peer(void)
{
	return g_peer_valid ? g_peer : (const uint8_t *)0;
}

void dbgauth_set_peer(const uint8_t mac[6])
{
	int i;

	for (i = 0; i < 6; i++)
		g_peer[i] = mac[i];
	g_peer_valid = 1;
}

#if defined(__aarch64__) && !defined(DBGAUTH_TEST_KEY)
static inline uint64_t cntpct(void)
{
	uint64_t v;

	__asm__ volatile("isb; mrs %0, cntpct_el0" : "=r"(v));
	return v;
}

static inline uint64_t cntfrq(void)
{
	uint64_t v;

	__asm__ volatile("mrs %0, cntfrq_el0" : "=r"(v));
	return v;
}
#else   /* hosted unit test (test_dbgauth.c) */
extern uint64_t cntpct(void);
static inline uint64_t cntfrq(void) { return 24000000u; }
#endif

static uint64_t g_pool[4];
static uint32_t g_pool_n;

void dbgauth_entropy(uint64_t v)
{
	uint64_t x = g_pool[g_pool_n & 3u] ^ v ^ cntpct();

	x ^= x >> 29; x *= 0xbf58476d1ce4e5b9ull; x ^= x >> 32;
	g_pool[g_pool_n & 3u] = (x << 13) | (x >> 51);
	g_pool_n++;
}

