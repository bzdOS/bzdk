#include "hmac_sha256.h"
/* Generated by the Makefile from the untracked key file
 * ($(DBG_AUTH_KEY_FILE), default ~/.config/bzdk/dbg.key). Defines
 * dbgauth_key[] and DBGAUTH_KEY_LEN. Never committed. */
#if defined(DBGAUTH_TEST_KEY)
/* test_dbgauth.c only: a fixed, public, obviously-not-secret key. */
#define DBGAUTH_KEY_LEN 32u
static const uint8_t dbgauth_key[32] = {
	0x74, 0x65, 0x73, 0x74, 0x2d, 0x6f, 0x6e, 0x6c, 0x79, 0x2d, 0x6e, 0x6f,
	0x74, 0x2d, 0x61, 0x2d, 0x72, 0x65, 0x61, 0x6c, 0x2d, 0x6b, 0x65, 0x79,
	0x2d, 0x62, 0x7a, 0x64, 0x6b, 0x2d, 0x30, 0x31 };
#else
#include "dbg_auth_key.h"
#endif

#define ETHERTYPE_CONSOLE 0x88B5u
#define T_HELLO 1u
#define T_CHAL  2u
#define T_DATA  3u
#define T_NAK   4u
#define DATA_HDR  36u     /* magic4 type1 chan1 sess4 ctr8 len2 tag16 */
#define TAGGED    20u     /* header bytes covered by the tag            */
#define TAG_LEN   16u
#define NSESS     16u

struct sess {
	uint32_t no;          /* 0 = free */
	uint32_t last_use;
	uint64_t last_ctr;
	uint8_t  ks[32];
};

static struct sess g_sess[NSESS];
static uint32_t g_sess_no;
static uint32_t g_use_tick;
static uint8_t  g_sb[16];
static int      g_sb_ready;
static uint64_t g_last_nak;

static void be32(uint8_t *p, uint32_t v)
{
	p[0] = (uint8_t)(v >> 24); p[1] = (uint8_t)(v >> 16);
	p[2] = (uint8_t)(v >> 8);  p[3] = (uint8_t)v;
}

static uint32_t rd_be32(const uint8_t *p)
{
	return ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) |
	       ((uint32_t)p[2] << 8) | (uint32_t)p[3];
}

static int is_magic(const uint8_t *p)
{
	return p[0] == 0x00 && p[1] == 'B' && p[2] == 'Z' && p[3] == 'K';
}

static void put_magic(uint8_t *p, uint8_t type, uint8_t chan)
{
	p[0] = 0x00; p[1] = 'B'; p[2] = 'Z'; p[3] = 'K';
	p[4] = type; p[5] = chan;
}

/* Board nonce for this boot. Derived lazily on the first HELLO so the pool
 * has seen the arrival time (41.7 ns ticks) of every frame since boot --
 * LAN broadcasts, guest traffic, the host's own frames -- on top of the
 * multi-second PHY autoneg time sampled at init. Keyed, so it does not
 * expose the raw timings. */
static void ensure_sb(void)
{
	uint8_t msg[9 + 32 + 8 + 4];
	uint8_t out[32];
	uint32_t i, j;
	uint64_t now = cntpct();
	static const char lbl[] = "BZK1/boot";

	if (g_sb_ready)
		return;
	for (i = 0; i < 9; i++)
		msg[i] = (uint8_t)lbl[i];
	for (j = 0; j < 4; j++)
		for (i = 0; i < 8; i++)
			msg[9 + j * 8 + i] = (uint8_t)(g_pool[j] >> (8 * i));
	for (i = 0; i < 8; i++)
		msg[41 + i] = (uint8_t)(now >> (8 * i));
	be32(msg + 49, g_pool_n);
	hmac_sha256(dbgauth_key, DBGAUTH_KEY_LEN, msg, sizeof(msg), out);
	for (i = 0; i < 16; i++)
		g_sb[i] = out[i];
	/* Session numbers start at a per-boot random point: a host process
	 * still holding a session from an earlier boot then names a number
	 * this boot never issued (NOSESS -> NAK -> it re-handshakes), instead
	 * of colliding with a live one. */
	g_sess_no = rd_be32(out + 16);
	g_sb_ready = 1;
}

/* HMAC(K, label9 | Sb | sess | Nh) */
static void derive(const char *label, uint32_t sess, const uint8_t nh[16],
		   uint8_t out[32])
{
	uint8_t msg[9 + 16 + 4 + 16];
	uint32_t i;

	for (i = 0; i < 9; i++)
		msg[i] = (uint8_t)label[i];
	for (i = 0; i < 16; i++)
		msg[9 + i] = g_sb[i];
	be32(msg + 25, sess);
	for (i = 0; i < 16; i++)
		msg[29 + i] = nh[i];
	hmac_sha256(dbgauth_key, DBGAUTH_KEY_LEN, msg, sizeof(msg), out);
}

static void do_hello(const uint8_t *src, const uint8_t *p)
{
	const uint8_t *nh = p + 6;
	struct sess *s = &g_sess[0];
	uint8_t reply[6 + 4 + 16 + 16 + 16];
	uint8_t proof[32];
	uint32_t i, no;

	ensure_sb();
	no = ++g_sess_no;
	if (no == 0)
		no = ++g_sess_no;
	/* free slot first, else least recently used */
	for (i = 0; i < NSESS; i++) {
		if (g_sess[i].no == 0) { s = &g_sess[i]; break; }
		if (g_sess[i].last_use < s->last_use)
			s = &g_sess[i];
	}
	if (s->no != 0)
		g_stats[DBGAUTH_ST_EVICT]++;
	s->no = no;
	s->last_ctr = 0;
	s->last_use = ++g_use_tick;
	derive("BZK1/sess", no, nh, s->ks);
	derive("BZK1/chal", no, nh, proof);

	put_magic(reply, T_CHAL, 0);
	be32(reply + 6, no);
	for (i = 0; i < 16; i++) {
		reply[10 + i] = g_sb[i];
		reply[26 + i] = nh[i];
		reply[42 + i] = proof[i];
	}
	g_stats[DBGAUTH_ST_HELLO]++;
	(void)emac_send_frame_to(src, ETHERTYPE_CONSOLE, reply,
				 (uint16_t)sizeof(reply));
}

static void do_nak(const uint8_t *src, uint8_t chan, uint32_t sess)
{
	uint8_t reply[10];
	uint64_t now = cntpct(), freq = cntfrq();

	if (g_last_nak && now - g_last_nak < freq / 50u)
		return;                 /* at most one NAK per 20 ms */
	g_last_nak = now;
	put_magic(reply, T_NAK, chan);
	be32(reply + 6, sess);
	g_stats[DBGAUTH_ST_NAKS]++;
	(void)emac_send_frame_to(src, ETHERTYPE_CONSOLE, reply,
				 (uint16_t)sizeof(reply));
}

int dbgauth_rx(const uint8_t *frame, uint32_t len, uint8_t *chan,
	       const uint8_t **inner, uint32_t *inner_len)
{
	const uint8_t *src = frame + 6;
	const uint8_t *p = frame + 14;
	uint32_t plen, sess, n, i;
	uint64_t ctr;
	uint8_t tag[32];
	uint8_t diff;
	struct sess *s = 0;
	uint64_t t0;

	if (len < 14 + 6)
		return DBGAUTH_NOT_ENVELOPE;
	plen = len - 14;
	if (!is_magic(p))
		return DBGAUTH_NOT_ENVELOPE;

	if (p[4] == T_HELLO) {
		if (plen < 6 + 16) {
			g_stats[DBGAUTH_ST_MALFORMED]++;
			return DBGAUTH_CONSUMED;
		}
		do_hello(src, p);
		return DBGAUTH_CONSUMED;
	}
	if (p[4] != T_DATA || plen < DATA_HDR) {
		/* CHAL/NAK are HV->host only; anything else is junk */
		g_stats[DBGAUTH_ST_MALFORMED]++;
		return DBGAUTH_CONSUMED;
	}

	sess = rd_be32(p + 6);
	ctr = ((uint64_t)rd_be32(p + 10) << 32) | rd_be32(p + 14);
	n = ((uint32_t)p[18] << 8) | p[19];
	if (n > plen - DATA_HDR) {
		g_stats[DBGAUTH_ST_MALFORMED]++;
		return DBGAUTH_CONSUMED;
	}
	for (i = 0; sess != 0 && i < NSESS; i++)
		if (g_sess[i].no == sess) { s = &g_sess[i]; break; }
	if (!s) {
		g_stats[DBGAUTH_ST_NOSESS]++;
		do_nak(src, p[5], sess);
		return DBGAUTH_CONSUMED;
	}

	t0 = cntpct();
	hmac_sha256_2(s->ks, 32, p, TAGGED, p + DATA_HDR, n, tag);
	diff = 0;
	for (i = 0; i < TAG_LEN; i++)
		diff |= (uint8_t)(tag[i] ^ p[TAGGED + i]);
	g_stats[DBGAUTH_ST_VERIFY_TICKS] = (uint32_t)(cntpct() - t0);
	g_stats[DBGAUTH_ST_VERIFY_LEN] = n;
	if (diff) {
		/* NAK this too: a sender with a stale key for a live session
		 * number re-handshakes instead of failing silently forever. The
		 * NAK goes to the frame's source only, so a forger learns
		 * nothing and cannot disturb the session's real owner. */
		g_stats[DBGAUTH_ST_BADTAG]++;
		do_nak(src, p[5], sess);
		return DBGAUTH_CONSUMED;
	}
	if (ctr <= s->last_ctr) {
		g_stats[DBGAUTH_ST_REPLAY]++;
		return DBGAUTH_CONSUMED;
	}
	s->last_ctr = ctr;
	s->last_use = ++g_use_tick;
	g_stats[DBGAUTH_ST_OK]++;
	dbgauth_set_peer(src);
	*chan = p[5];
	*inner = p + DATA_HDR;
	*inner_len = n;
	return DBGAUTH_ACCEPT;
}

