/* fb.c — pixel/rect/text drawing layer implementation. See fb.h for the
 * API contract.
 *
 * Freestanding: only <stdint.h> and "fb.h". No libc, no floats. Every fill
 * is a manual pixel/word loop (never memset/memcpy) so nothing pulls in a
 * libgcc/NEON helper under -mgeneral-regs-only.
 *
 * Pixel format: 32-bit 0xAARRGGBB (matches DE2's XRGB8888 UI-layer format
 * in hdmi.c — the alpha byte is written through untouched, the display
 * engine ignores it for an opaque full-screen layer).
 */
#include <stdint.h>
#include "fb.h"

