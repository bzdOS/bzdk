/* ------------------------------------------------------------------ */
/* Surface state                                                       */
/* ------------------------------------------------------------------ */
static volatile uint32_t *g_base;
static int g_width, g_height, g_stride;
static int g_ready;

/* Dirty pixel-row range [g_dirty_y0, g_dirty_y1] (inclusive) accumulated
 * since the last fb_flush(); g_dirty_y0 < 0 means "nothing dirty". */
static int g_dirty_y0 = -1;
static int g_dirty_y1 = -1;

static void mark_dirty(int y0, int y1)
{
	if (y0 < 0)
		y0 = 0;
	if (y1 >= g_height)
		y1 = g_height - 1;
	if (y1 < y0)
		return;

	if (g_dirty_y0 < 0 || y0 < g_dirty_y0)
		g_dirty_y0 = y0;
	if (y1 > g_dirty_y1)
		g_dirty_y1 = y1;
}

void fb_init(uint32_t *base, int w, int h, int stride)
{
	g_ready = 0;

	if (base == (uint32_t *)0)
		return;
	if (w < FB_MIN_DIM || w > FB_MAX_DIM)
		return;
	if (h < FB_MIN_DIM || h > FB_MAX_DIM)
		return;
	if (stride < w || stride > FB_MAX_DIM)
		return;

	g_base = (volatile uint32_t *)base;
	g_width = w;
	g_height = h;
	g_stride = stride;

	g_dirty_y0 = -1;
	g_dirty_y1 = -1;

	g_ready = 1;
}

int fb_ready(void)
{
	return g_ready;
}

void fb_pixel(int x, int y, uint32_t argb)
{
	if (!g_ready)
		return;
	if ((unsigned)x >= (unsigned)g_width || (unsigned)y >= (unsigned)g_height)
		return;

	g_base[(int64_t)y * g_stride + x] = argb;
	mark_dirty(y, y);
}

void fb_clear(uint32_t argb)
{
	int x, y;

	if (!g_ready)
		return;

	for (y = 0; y < g_height; y++) {
		volatile uint32_t *row = &g_base[(int64_t)y * g_stride];
		for (x = 0; x < g_width; x++)
			row[x] = argb;
	}

	mark_dirty(0, g_height - 1);
}

void fb_fillrect(int x, int y, int w, int h, uint32_t argb)
{
	int x0, y0, x1, y1, xx, yy;

	if (!g_ready || w <= 0 || h <= 0)
		return;

	x0 = x;
	y0 = y;
	x1 = x + w; /* exclusive */
	y1 = y + h;

	if (x0 < 0)
		x0 = 0;
	if (y0 < 0)
		y0 = 0;
	if (x1 > g_width)
		x1 = g_width;
	if (y1 > g_height)
		y1 = g_height;
	if (x0 >= x1 || y0 >= y1)
		return;

	for (yy = y0; yy < y1; yy++) {
		volatile uint32_t *row = &g_base[(int64_t)yy * g_stride];
		for (xx = x0; xx < x1; xx++)
			row[xx] = argb;
	}

	mark_dirty(y0, y1 - 1);
}

void fb_rect(int x, int y, int w, int h, uint32_t argb)
{
	if (!g_ready || w <= 0 || h <= 0)
		return;

	fb_fillrect(x, y, w, 1, argb);              /* top */
	fb_fillrect(x, y + h - 1, w, 1, argb);       /* bottom */
	fb_fillrect(x, y, 1, h, argb);               /* left */
	fb_fillrect(x + w - 1, y, 1, h, argb);       /* right */
}

void fb_char(int x, int y, char c, uint32_t fg, uint32_t bg)
{
	const uint8_t *bitmap;
	unsigned char ch = (unsigned char)c;
	int row, col;

	if (!g_ready)
		return;

	if (ch >= 0x20 && ch <= 0x7E)
		bitmap = &font[(unsigned)(ch - 0x20) * FB_FONT_H];
	else
		bitmap = (const uint8_t *)0;

	for (row = 0; row < FB_FONT_H; row++) {
		uint8_t bits = bitmap ? bitmap[row] : 0;

		for (col = 0; col < FB_FONT_W; col++)
			fb_pixel(x + col, y + row,
				 (bits & (1u << col)) ? fg : bg);
	}
}

void fb_str(int x, int y, const char *s, uint32_t fg, uint32_t bg)
{
	int cx = x;

	if (!g_ready || !s)
		return;

	while (*s) {
		fb_char(cx, y, *s, fg, bg);
		cx += FB_FONT_W;
		s++;
	}
}

void fb_hex(int x, int y, uint64_t v, int ndigits, uint32_t fg, uint32_t bg)
{
	static const char hexdig[16] = "0123456789ABCDEF";
	int i;
	int cx = x;

	if (!g_ready)
		return;
	if (ndigits < 1)
		ndigits = 1;
	if (ndigits > 16)
		ndigits = 16;

	for (i = ndigits - 1; i >= 0; i--) {
		uint32_t nib = (uint32_t)((v >> (i * 4)) & 0xFu);
		fb_char(cx, y, hexdig[nib], fg, bg);
		cx += FB_FONT_W;
	}
}

int fb_dec(int x, int y, uint64_t v, uint32_t fg, uint32_t bg)
{
	char digits[20];
	int n = 0;
	int i;
	int cx = x;

	if (!g_ready)
		return 0;

	if (v == 0) {
		digits[n++] = '0';
	} else {
		while (v > 0 && n < (int)sizeof(digits)) {
			digits[n++] = (char)('0' + (int)(v % 10u));
			v /= 10u;
		}
	}

	/* digits[] was filled least-significant-first; draw MS-first. */
	for (i = n - 1; i >= 0; i--) {
		fb_char(cx, y, digits[i], fg, bg);
		cx += FB_FONT_W;
	}

	return n;
}

void fb_flush(void)
{
	uint64_t ctr, line, start, end, addr;

	__asm__ volatile("dsb sy" ::: "memory");

	if (!g_ready || g_dirty_y0 < 0 || g_dirty_y1 < g_dirty_y0) {
		g_dirty_y0 = -1;
		g_dirty_y1 = -1;
		return;
	}

	/* CTR_EL0.DminLine (bits[19:16]): log2 of the smallest data cache
	 * line, in 4-byte words. line_bytes = 4 << DminLine (64 bytes on
	 * Cortex-A53, the A64's core). */
	__asm__ volatile("mrs %0, ctr_el0" : "=r"(ctr));
	line = (uint64_t)4 << ((ctr >> 16) & 0xFu);
	if (line == 0)
		line = 64;

	start = (uint64_t)(uintptr_t)&g_base[(int64_t)g_dirty_y0 * g_stride];
	end = (uint64_t)(uintptr_t)&g_base[(int64_t)(g_dirty_y1 + 1) * g_stride];

	start &= ~(line - 1);
	end = (end + line - 1) & ~(line - 1);

	for (addr = start; addr < end; addr += line)
		__asm__ volatile("dc civac, %0" : : "r"(addr) : "memory");

	__asm__ volatile("dsb sy" ::: "memory");

	g_dirty_y0 = -1;
	g_dirty_y1 = -1;
}
